# A REALLY FUCKING GROSS HACK!!!!

# Having multiple scripts would be cubersome for endusers to set up Palette (because now endusers
# would have to manually edit each and every file to alter the "palette_scripts" directory to
# prevent mod conflicts should two mods use Palette.
#
# There's several Lua bundlers out there, however, many of them have not been updated for years and
# Only work with `require`, whereas we use `include`. This ugly Python code transforms all of our
# needed lua files and bundles it into a singular lua file for easy distribution.
#
# This is obviously REALLY fucking hardcoded for this library. If you're a Python wiz reading this,
# I'm so so sorry. *hic* *sob*

from pathlib import Path

root = Path(__file__).resolve().parent.parent
output = root / "dist" / "palette.lua"

modules = {
    "palette_scripts.palette_utils": "palette_scripts/palette_utils.lua",
    "palette_scripts.palette_gradient": "palette_scripts/palette_gradient.lua",
    "palette_scripts.particle_emitter": "palette_scripts/particle_emitter.lua",
    "palette_scripts.palette_keyframes": "palette_scripts/palette_keyframes.lua",
    "palette_scripts.palette_over_lifetime": "palette_scripts/palette_over_lifetime.lua",
    "palette_scripts.palette_shape": "palette_scripts/palette_shape.lua",
    "palette_scripts.palette_noise": "palette_scripts/palette_noise.lua"
}

# Remove ---@meta tag so the final bundled Lua script isn't treated as a script only for type defs.
annotations = (root / "palette_scripts/palette_classes.d.lua").read_text(encoding="utf-8")
annotations = annotations.replace("---@meta", "")

parts = [
    """
-- THIS FILE IS AUTOMATICALLY GENERATED AND IS NOT MEANT TO BE EDITED!!!"
-- If you wish to contribute to new features or see the actual source code, you can get it from
-- The GitHub repository here: https://github.com/Syntax-Sculptor/Palette
    
    """,
    annotations,
    "local include",
    "local modules = {",
]

# Put each script into a function
for name, filename in modules.items():
    source = (root / filename).read_text(encoding="utf-8")

    parts.append(f'    ["{name}"] = function()')
    parts.append(source)
    parts.append("    end,")

parts.append("}")

parts.append("""
include = function(name)
    local module = modules[name]
    assert(module, "Unknown bundled module: " .. tostring(name))
    return module()
end
""")

parts.append((root / "palette_scripts" / "palette.lua").read_text(encoding="utf-8"))

output.parent.mkdir(parents=True, exist_ok=True)
output.write_text("\n\n".join(parts) + "\n", encoding="utf-8")

